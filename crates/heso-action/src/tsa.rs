    /// A token whose genTime falls OUTSIDE the signer cert's validity window must
    /// fail closed — proving the offline notBefore<=genTime<=notAfter check using
    /// the token's own genTime (never wall-clock).
    #[test]
    fn gen_time_outside_cert_window_fails_closed() {
        let h = action_hash();
        // Build certs valid around TEST_GEN_TIME_SECS but a TSTInfo whose genTime is
        // ~3 years later (outside the ±1y window).
        let root_signing = rsa_key(b"heso-test-window-root");
        let signer_signing = rsa_key(b"heso-test-window-signer");
        let root = make_root(&root_signing, &cn("HESO Window Root"));
        let signer = make_tsa_signer(
            &root,
            &root_signing,
            &signer_signing,
            &cn("HESO Window TSA"),
            true,
        );
        let tst = tst_info_der_at(
            &sha256_imprint(&h),
            ID_SHA256,
            TEST_GEN_TIME_SECS + 3 * 365 * 24 * 3600,
        );
        let token = mint_token(&tst, &signer, &signer_signing);
        let root_der = root.to_der().unwrap();
        let err = tsa_crypto::verify(&token, &h, &[root_der.as_slice()]).unwrap_err();
        assert!(
            err.contains("expired at the token genTime")
                || err.contains("not yet valid at the token genTime"),
            "got: {err}"
        );
    }
