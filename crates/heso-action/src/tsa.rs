//! RFC-3161 trusted-time anchoring — the VERIFY side (always on, fail-closed)
//! and a feature-gated producer.
//!
//! A [`crate::receipt::TimeAnchor`] is an independent "existed-no-later-than"
//! bound over a receipt's `action_hash`: a TSA (Time-Stamping Authority) signs a
//! token attesting it saw that hash at a given time. `captured_at` is the
//! operator's own clock and is NOT trusted; the anchor is the non-operator
//! countersignature that is.
//!
//! ## Two layers, one contract
//!
//! [`verify_time_anchor`] is the entry point the verifier calls. It is ALWAYS
//! compiled and ALWAYS fails closed:
//!
//! - **Always-on preconditions** (no crypto deps): the anchor `kind` must be
//!   [`TIME_ANCHOR_RFC3161`], `anchored_hash` must be 64-lowercase-hex AND equal
//!   the receipt's recomputed `action_hash`, and `token_b64` must be non-empty
//!   valid base64. These catch the cheap forgeries with zero dependencies.
//! - **Cryptographic verification** of the CMS `SignedData` / `TSTInfo`
//!   (parsing the DER token, checking its `messageImprint` is `action_hash`,
//!   verifying the TSA signature, chaining the TSA cert to a **pinned in-binary
//!   root**, and requiring the `id-kp-timeStamping` EKU) is compiled ONLY under
//!   the `tsa` cargo feature, which pulls the RustCrypto ASN.1 stack.
//!
//! With the `tsa` feature OFF, a *present* anchor that passes the preconditions
//! cannot be cryptographically checked — so it FAILS CLOSED
//! ([`Err`] → [`crate::verify::ActionOutcome::TimeAnchorUnverifiable`]) rather
//! than being vouched for. The default zero-dep build therefore never asserts
//! trusted time it cannot prove; turning on `tsa` is what lets a present anchor
//! verify to `Ok`.
//!
//! ## Pinned TSA roots
//!
//! Trust is anchored to a small set of roots compiled into the binary
//! ([`PINNED_TSA_ROOTS`]), never to the `tsa` string in the anchor (which is
//! informational). This is the same "pin the verifier's trust, don't take it
//! from the artifact" discipline the rest of HESO uses.

use crate::domain::TIME_ANCHOR_RFC3161;
use crate::receipt::TimeAnchor;
use base64::engine::general_purpose::STANDARD as B64;
use base64::Engine as _;

// The DER bytes of the TSA root certificates this verifier trusts, pinned into
// the binary as `pub static PINNED_TSA_ROOTS: &[&[u8]]`. Trust is decided against
// THESE, never against the anchor's `tsa` string.
//
// Under the `tsa` feature this is generated by `build.rs` from `roots/*.der` +
// `roots/roots.toml`: each root is parsed as X.509 and its SHA-256 is asserted
// equal to the manifest pin AT COMPILE TIME (the build fails on drift). The set
// currently pins DigiCert Trusted Root G4, DigiCert Assured ID Root CA, and the
// Free TSA root. With the feature OFF there is no crypto stack to chain with, so
// the slice is EMPTY (below) — no placeholder bytes are ever embedded.
//
// The `pinned_root_count` accessor lets the always-on layer and tests assert the
// pin set without depending on the `tsa` crypto stack; the actual chaining
// against these only runs under the `tsa` feature.
#[cfg(feature = "tsa")]
include!(concat!(env!("OUT_DIR"), "/pinned_tsa_roots.rs"));

/// With the `tsa` feature OFF there is no verifier and therefore no trust set.
#[cfg(not(feature = "tsa"))]
pub static PINNED_TSA_ROOTS: &[&[u8]] = &[];

/// Number of pinned TSA roots — surfaced so the always-on layer and tests can
/// assert the pin set is present without parsing certificates.
pub fn pinned_root_count() -> usize {
    PINNED_TSA_ROOTS.len()
}

/// Verify a present [`TimeAnchor`] against the receipt's `action_hash`.
///
/// Returns `Ok(gen_time)` (the TSA-asserted RFC-3161 `genTime`, empty when the
/// `tsa` feature did not extract it) when the anchor is trustworthy, or
/// `Err(reason)` — FAIL CLOSED — on any problem. The caller
/// ([`crate::verify::open_receipt`]) maps `Err` to
/// [`crate::verify::ActionOutcome::TimeAnchorUnverifiable`].
///
/// `action_hash` MUST already be the verifier's recomputed self-hash (verify
/// checks the hash before this runs), so binding the anchor to it binds it to the
/// authenticated content.
pub fn verify_time_anchor(anchor: &TimeAnchor, action_hash: &str) -> Result<String, String> {
    // --- Always-on preconditions (no crypto deps) ---------------------------
    if anchor.kind != TIME_ANCHOR_RFC3161 {
        return Err(format!(
            "time_anchor kind `{}` is not supported (expected `{TIME_ANCHOR_RFC3161}`)",
            anchor.kind
        ));
    }
    if !is_64_lower_hex(&anchor.anchored_hash) {
        return Err("time_anchor anchored_hash is not 64 lowercase-hex".to_string());
    }
    // The anchor must be over THIS receipt's authenticated hash — not some other.
    if anchor.anchored_hash != action_hash {
        return Err(format!(
            "time_anchor anchored_hash {} does not match action_hash {action_hash}",
            anchor.anchored_hash
        ));
    }
    let token = B64
        .decode(anchor.token_b64.as_bytes())
        .map_err(|_| "time_anchor token_b64 is not valid base64".to_string())?;
    if token.is_empty() {
        return Err("time_anchor token_b64 decoded to empty".to_string());
    }

    // --- Cryptographic verification (feature-gated) -------------------------
    verify_token_crypto(&token, action_hash)
}

/// 64 lowercase-hex predicate (shared with the redaction check's discipline).
fn is_64_lower_hex(s: &str) -> bool {
    s.len() == 64 && s.chars().all(|c| c.is_ascii_hexdigit() && !c.is_ascii_uppercase())
}

// ============================================================================
// Cryptographic verification — feature-gated
// ============================================================================

/// With the `tsa` feature OFF: a present, precondition-passing anchor still
/// cannot be cryptographically checked, so it FAILS CLOSED. The default build
/// never vouches for trusted time it cannot verify.
#[cfg(not(feature = "tsa"))]
fn verify_token_crypto(_token: &[u8], _action_hash: &str) -> Result<String, String> {
    Err("time_anchor present but RFC-3161 verification is unavailable in this build \
         (rebuild heso-action with the `tsa` feature); failing closed"
        .to_string())
}

/// With the `tsa` feature ON: parse the DER CMS `SignedData`, confirm its
/// `TSTInfo.messageImprint` is `action_hash`, verify the TSA signature, chain the
/// signer cert to a pinned root, and require the `id-kp-timeStamping` EKU.
///
/// Returns the TSA `genTime` on success. This is the REAL verify path; it is
/// gated only because it pulls the RustCrypto ASN.1 stack (`cms`/`x509-cert`/
/// `der`/`rsa`/`sha2`), which heso-action keeps out of its zero-dep default.
#[cfg(feature = "tsa")]
fn verify_token_crypto(token: &[u8], action_hash: &str) -> Result<String, String> {
    tsa_crypto::verify(token, action_hash, PINNED_TSA_ROOTS)
}

/// The real RFC-3161 verifier, compiled only under the `tsa` feature.
#[cfg(feature = "tsa")]
mod tsa_crypto {
    use cms::content_info::ContentInfo;
    use cms::signed_data::{SignedData, SignerIdentifier, SignerInfo};
    use const_oid::db::rfc5280::ID_KP_TIME_STAMPING;
    use const_oid::ObjectIdentifier;
    use der::asn1::{GeneralizedTime, OctetString};
    use der::{Decode, DecodeValue, Encode, FixedTag, Header, Reader, Sequence, Tag};
    use x509_cert::spki::AlgorithmIdentifierOwned;
    use x509_cert::Certificate;

    /// OID for `id-ct-TSTInfo` (1.2.840.113549.1.9.16.1.4) — the CMS
    /// eContentType of an RFC-3161 timestamp token.
    const ID_CT_TST_INFO: &str = "1.2.840.113549.1.9.16.1.4";

    /// OID for the `message-digest` signed attribute (PKCS#9, 1.2.840.113549.1.9.4).
    const ID_MESSAGE_DIGEST: ObjectIdentifier =
        ObjectIdentifier::new_unwrap("1.2.840.113549.1.9.4");

    /// OID for `id-sha256` (2.16.840.1.101.3.4.2.1) — the
    /// `messageImprint.hashAlgorithm` HESO mints its tokens under.
    ///
    /// No public RFC-3161 TSA will sign a BLAKE3 imprint, so HESO anchors the
    /// SHA-256 *of the 32 raw BLAKE3 `action_hash` bytes*. This is NOT a
    /// weakening: the SHA-256 pre-image IS the already-authenticated
    /// `action_hash`, so the imprint binds 1:1 to it — `SHA-256(action_hash)`
    /// can only be produced from that exact hash. The verifier PINS this OID: a
    /// token whose imprint algorithm is anything else is refused.
    const ID_SHA256_OID: ObjectIdentifier =
        ObjectIdentifier::new_unwrap("2.16.840.1.101.3.4.2.1");

    /// `RFC-3161 MessageImprint ::= SEQUENCE { hashAlgorithm AlgorithmIdentifier,
    /// hashedMessage OCTET STRING }`.
    #[derive(Clone, Debug, Eq, PartialEq, Sequence)]
    struct MessageImprint {
        hash_algorithm: AlgorithmIdentifierOwned,
        hashed_message: OctetString,
    }

    /// A minimal `RFC-3161 TSTInfo` decoder — enough to read the messageImprint
    /// and genTime, the only fields the verifier trusts and keys on.
    ///
    /// `TSTInfo` is a SEQUENCE whose first five fields (version, policy,
    /// messageImprint, serialNumber, genTime) are required, followed by the
    /// OPTIONAL `accuracy`, `ordering` (DEFAULT FALSE), `nonce`, `[0] tsa` and
    /// `[1] extensions`. Every real public TSA emits some of those trailing
    /// fields. We therefore decode the required prefix and then DRAIN the rest:
    /// each remaining TLV is consumed and discarded so the SEQUENCE body is fully
    /// read. A `der::Sequence` derive cannot do this — it requires the whole body
    /// to map onto declared fields and fails as "trailing data" — so we implement
    /// `DecodeValue` by hand. Draining still parses the TLV framing (length-checked
    /// by the reader), so a truncated or malformed trailing field fails closed; we
    /// simply do not interpret fields we place no trust in.
    #[derive(Clone, Debug, Eq, PartialEq)]
    struct TstInfo {
        message_imprint: MessageImprint,
        gen_time: GeneralizedTime,
    }

    impl FixedTag for TstInfo {
        const TAG: Tag = Tag::Sequence;
    }

    impl<'a> DecodeValue<'a> for TstInfo {
        type Error = der::Error;

        fn decode_value<R: Reader<'a>>(reader: &mut R, _header: Header) -> der::Result<Self> {
            // version + policy precede the messageImprint; drain them by TLV
            // framing (we key on neither, and policy is a `MAX_SIZE`-generic OID
            // that does not infer in a bare `decode`).
            reader.tlv_bytes()?; // version
            reader.tlv_bytes()?; // policy
            let message_imprint = MessageImprint::decode(reader)?;
            let _serial_number = der::asn1::Int::decode(reader)?;
            let gen_time = GeneralizedTime::decode(reader)?;
            // Drain the trailing OPTIONAL fields (accuracy/ordering/nonce/tsa/
            // extensions). `tlv_bytes` reads one full TLV and advances the reader;
            // when the body is exhausted the blanket `Decode` impl's `finish()`
            // sees no leftover and succeeds.
            while !reader.is_finished() {
                reader.tlv_bytes()?;
            }
            Ok(Self { message_imprint, gen_time })
        }
    }

    /// Verify a DER RFC-3161 token. See [`super::verify_token_crypto`].
    pub fn verify(token: &[u8], action_hash: &str, roots: &[&[u8]]) -> Result<String, String> {
        // 1. Parse the outer CMS ContentInfo → SignedData.
        let ci = ContentInfo::from_der(token)
            .map_err(|e| format!("RFC-3161 token is not valid CMS ContentInfo: {e}"))?;
        let sd = ci
            .content
            .decode_as::<SignedData>()
            .map_err(|e| format!("CMS content is not SignedData: {e}"))?;

        // 2. The eContentType must be id-ct-TSTInfo and carry the TSTInfo bytes.
        let econtent = sd
            .encap_content_info
            .econtent
            .as_ref()
            .ok_or_else(|| "SignedData has no eContent (detached TSTInfo unsupported)".to_string())?;
        if sd.encap_content_info.econtent_type.to_string() != ID_CT_TST_INFO {
            return Err(format!(
                "eContentType {} is not id-ct-TSTInfo",
                sd.encap_content_info.econtent_type
            ));
        }
        let tst_info_der = econtent
            .value()
            .to_vec();

        // 3. The TSTInfo.messageImprint hashedMessage must be SHA-256(action_hash).
        //    We keep the parsed genTime to window cert validity offline.
        let (gen_time_display, gen_time) = check_message_imprint(&tst_info_der, action_hash)?;

        // 4. Find the signer certificate (by SignerInfo sid), require the
        //    timeStamping EKU, and build a bounded path from it through any
        //    embedded intermediates to a pinned root, validating each cert's
        //    validity window against the token's OWN genTime (never wall-clock).
        let signer_cert = signer_certificate(&sd)?;
        require_timestamping_eku(&signer_cert)?;
        chain_to_pinned_root(&signer_cert, &sd, roots, &gen_time)?;

        // 5. Verify the TSA signature over the SignedAttributes (RSA/ECDSA).
        verify_signer_signature(&sd, &signer_cert)?;

        Ok(gen_time_display)
    }

    /// Decode TSTInfo far enough to read messageImprint.hashedMessage and
    /// genTime; confirm the imprint equals `SHA-256(action_hash_bytes)` — the
    /// SHA-256 of the 32 raw BLAKE3 bytes of the receipt's `action_hash`.
    ///
    /// Returns `(gen_time_display, gen_time)` so callers that need the parsed
    /// `GeneralizedTime` for cert-validity windowing get it without re-parsing.
    fn check_message_imprint(
        tst_info_der: &[u8],
        action_hash: &str,
    ) -> Result<(String, GeneralizedTime), String> {
        use sha2::Digest;

        let tst = TstInfo::from_der(tst_info_der)
            .map_err(|e| format!("TSTInfo is not valid DER: {e}"))?;

        // PIN the imprint hash algorithm to id-sha256. No public RFC-3161 TSA
        // signs a BLAKE3 imprint; HESO anchors SHA-256 OVER the raw BLAKE3
        // action_hash bytes. A token whose imprint algorithm is anything else is
        // refused, so a token minted over a different digest cannot ride along.
        if tst.message_imprint.hash_algorithm.oid != ID_SHA256_OID {
            return Err(format!(
                "messageImprint hashAlgorithm {} is not the expected id-sha256 OID {ID_SHA256_OID}",
                tst.message_imprint.hash_algorithm.oid
            ));
        }

        // The anchored hash is a 64-hex BLAKE3 digest (32 raw bytes). The imprint
        // commits to SHA-256(those 32 bytes) — which binds 1:1 to the
        // authenticated action_hash (only that hash produces this imprint).
        let raw = hex_to_32(action_hash)
            .ok_or_else(|| "action_hash is not 64-hex (32 bytes)".to_string())?;
        let want = sha2::Sha256::digest(raw);
        if tst.message_imprint.hashed_message.as_bytes() != want.as_slice() {
            return Err(
                "messageImprint hashedMessage does not equal SHA-256(action_hash)".to_string(),
            );
        }

        // The TSA-asserted genTime, rendered as an RFC3339-ish string for display,
        // plus the parsed value for cert-validity windowing.
        Ok((tst.gen_time.to_date_time().to_string(), tst.gen_time))
    }

    /// Decode a 64-char lowercase-hex string into 32 raw bytes, or `None` if it is
    /// not exactly 64 hex chars.
    fn hex_to_32(s: &str) -> Option<[u8; 32]> {
        if s.len() != 64 {
            return None;
        }
        let mut out = [0u8; 32];
        let bytes = s.as_bytes();
        for (i, slot) in out.iter_mut().enumerate() {
            let hi = (bytes[2 * i] as char).to_digit(16)?;
            let lo = (bytes[2 * i + 1] as char).to_digit(16)?;
            *slot = (hi * 16 + lo) as u8;
        }
        Some(out)
    }

    /// Collect every embedded X.509 certificate from the SignedData. These are
    /// UNTRUSTED path material: the leaf signer plus any intermediates a real TSA
    /// token bundles. Trust comes only from chaining up to a pinned root.
    fn collect_certificates(sd: &SignedData) -> Result<Vec<Certificate>, String> {
        let certs = sd
            .certificates
            .as_ref()
            .ok_or_else(|| "SignedData carries no certificates".to_string())?;
        let mut out = Vec::new();
        for cert_choice in certs.0.iter() {
            if let cms::cert::CertificateChoices::Certificate(c) = cert_choice {
                out.push(c.clone());
            }
        }
        if out.is_empty() {
            return Err("SignedData has no X.509 certificate".to_string());
        }
        Ok(out)
    }

    /// Pick the LEAF signer certificate, matching the (single) SignerInfo's `sid`
    /// against the embedded certs. We support the `IssuerAndSerialNumber` sid form
    /// (what RFC-3161 tokens use); `SubjectKeyIdentifier` is unsupported (fail
    /// closed). Selecting by sid (not "the first cert") means a token that lists
    /// the chain in any order, or includes the responder among intermediates, is
    /// still bound to the cert that actually signed.
    fn signer_certificate(sd: &SignedData) -> Result<Certificate, String> {
        let signer_info: &SignerInfo = sd
            .signer_infos
            .0
            .as_slice()
            .first()
            .ok_or_else(|| "SignedData carries no SignerInfo".to_string())?;
        let certs = collect_certificates(sd)?;

        match &signer_info.sid {
            SignerIdentifier::IssuerAndSerialNumber(ias) => {
                for c in &certs {
                    let tbs = c.tbs_certificate();
                    if tbs.issuer() == &ias.issuer && tbs.serial_number() == &ias.serial_number {
                        return Ok(c.clone());
                    }
                }
                Err("no embedded certificate matches the SignerInfo issuer+serial".to_string())
            }
            SignerIdentifier::SubjectKeyIdentifier(_) => {
                Err("SignerInfo sid uses SubjectKeyIdentifier (unsupported); failing closed"
                    .to_string())
            }
        }
    }

    fn require_timestamping_eku(cert: &Certificate) -> Result<(), String> {
        let exts = cert
            .tbs_certificate()
            .extensions()
            .ok_or_else(|| "TSA certificate has no extensions".to_string())?;
        for ext in exts.iter() {
            if ext.extn_id == const_oid::db::rfc5280::ID_CE_EXT_KEY_USAGE {
                use x509_cert::ext::pkix::ExtendedKeyUsage;
                let eku = ExtendedKeyUsage::from_der(ext.extn_value.as_bytes())
                    .map_err(|e| format!("malformed EKU extension: {e}"))?;
                if eku.0.contains(&ID_KP_TIME_STAMPING) {
                    return Ok(());
                }
                return Err("TSA certificate EKU lacks id-kp-timeStamping".to_string());
            }
        }
        Err("TSA certificate has no Extended Key Usage extension".to_string())
    }

    /// Max certificates in a path (leaf + intermediates + root). RFC-3161 TSA
    /// tokens are shallow (DigiCert is leaf→intermediate→root); 4 leaves headroom
    /// while bounding work and refusing pathological/looping inputs.
    const MAX_CHAIN_DEPTH: usize = 4;

    /// Build a bounded path from the leaf signer cert, walking issuer-by-name
    /// through any embedded intermediates, to a PINNED root. Every cert on the
    /// path is validated:
    ///
    /// - its `notBefore <= genTime <= notAfter` window contains the token's OWN
    ///   `genTime` (NEVER wall-clock — verification stays offline + deterministic),
    /// - each hop's signature verifies under its issuer's key (name binding alone
    ///   is never trusted), RSA or ECDSA.
    ///
    /// Depth is capped at [`MAX_CHAIN_DEPTH`] and a visited-set rejects cycles.
    /// Terminates ONLY when a cert is issued by (and signature-verifies under) a
    /// pinned root; anything else fails closed.
    fn chain_to_pinned_root(
        leaf: &Certificate,
        sd: &SignedData,
        roots: &[&[u8]],
        gen_time: &GeneralizedTime,
    ) -> Result<(), String> {
        // Parse the pinned roots once. An unparseable pin is not a trust anchor.
        let pinned: Vec<Certificate> = roots
            .iter()
            .filter_map(|r| Certificate::from_der(r).ok())
            .collect();
        if pinned.is_empty() {
            return Err("no parseable pinned TSA root configured; failing closed".to_string());
        }

        let intermediates = collect_certificates(sd)?;

        // Walk: current cert -> issuer. At each step, first try to terminate at a
        // pinned root; else find an embedded intermediate whose subject matches the
        // current issuer and continue. Validity-window + signature checked per hop.
        let mut current = leaf.clone();
        let mut visited: Vec<Vec<u8>> = Vec::new();

        for _depth in 0..MAX_CHAIN_DEPTH {
            // Reject cycles: a cert (by its DER) may appear at most once on a path.
            let cur_der = current
                .to_der()
                .map_err(|e| format!("re-encoding cert on path failed: {e}"))?;
            if visited.iter().any(|v| v == &cur_der) {
                return Err("certificate path contains a cycle; failing closed".to_string());
            }
            visited.push(cur_der);

            // The current cert must itself be valid at genTime.
            check_validity_window(&current, gen_time)?;

            // (a) Try to terminate: is `current` issued by a pinned root?
            for root in &pinned {
                if current.tbs_certificate().issuer() != root.tbs_certificate().subject() {
                    continue;
                }
                // The pinned root must also be valid at genTime, and must actually
                // have signed `current`.
                check_validity_window(root, gen_time)?;
                if verify_cert_signed_by(&current, root).is_ok() {
                    return Ok(());
                }
            }

            // (b) Otherwise step to an embedded intermediate that issued `current`.
            let issuer_name = current.tbs_certificate().issuer().clone();
            let next = intermediates.iter().find(|cand| {
                // The candidate's subject must be the current issuer, it must not be
                // `current` itself (self-issued non-root would loop), and it must
                // have actually signed `current`.
                cand.tbs_certificate().subject() == &issuer_name
                    && cand.tbs_certificate().subject() != current.tbs_certificate().subject()
                    && verify_cert_signed_by(&current, cand).is_ok()
            });

            match next {
                Some(parent) => current = parent.clone(),
                None => {
                    return Err(
                        "TSA cert path does not reach any pinned root (no issuer found / \
                         signature mismatch); failing closed"
                            .to_string(),
                    );
                }
            }
        }

        Err(format!(
            "TSA cert path exceeded max depth {MAX_CHAIN_DEPTH} without reaching a pinned root; \
             failing closed"
        ))
    }

    /// Validate `cert`'s `notBefore <= genTime <= notAfter` window using the
    /// token's OWN genTime. This keeps verification fully offline and
    /// deterministic — we never consult the wall clock.
    fn check_validity_window(cert: &Certificate, gen_time: &GeneralizedTime) -> Result<(), String> {
        let validity = cert.tbs_certificate().validity();
        let not_before = validity.not_before.to_unix_duration();
        let not_after = validity.not_after.to_unix_duration();
        let at = gen_time.to_unix_duration();
        if at < not_before {
            return Err("a certificate on the path is not yet valid at the token genTime".to_string());
        }
        if at > not_after {
            return Err("a certificate on the path is expired at the token genTime".to_string());
        }
        Ok(())
    }

    /// Verify `cert`'s signature was produced by `issuer`'s public key. RSA
    /// PKCS#1 v1.5 OR ECDSA (P-256/P-384) over the re-encoded TBSCertificate,
    /// dispatched on `cert`'s `signatureAlgorithm`.
    fn verify_cert_signed_by(cert: &Certificate, issuer: &Certificate) -> Result<(), String> {
        let tbs_der = cert
            .tbs_certificate()
            .to_der()
            .map_err(|e| format!("re-encoding TBSCertificate failed: {e}"))?;
        let sig = cert
            .signature()
            .as_bytes()
            .ok_or_else(|| "certificate signature is not a whole number of bytes".to_string())?;
        let spki = issuer.tbs_certificate().subject_public_key_info();
        // A certificate always names the full hash-and-key algorithm (e.g.
        // sha256WithRSAEncryption), so there is no separate digest OID to resolve.
        verify_signature(&cert.signature_algorithm().oid, None, spki, &tbs_der, sig)
    }

    fn verify_signer_signature(sd: &SignedData, cert: &Certificate) -> Result<(), String> {
        let signer_info: &SignerInfo = sd
            .signer_infos
            .0
            .as_slice()
            .first()
            .ok_or_else(|| "SignedData carries no SignerInfo".to_string())?;

        // The eContent (the TSTInfo bytes) the signature commits to.
        let econtent = sd
            .encap_content_info
            .econtent
            .as_ref()
            .ok_or_else(|| "SignedData has no eContent".to_string())?;
        let econtent_value = econtent.value();

        let signed_message = match signer_info.signed_attrs.as_ref() {
            // CMS with signed attributes: the `message-digest` attribute MUST equal
            // digest(eContent), and the signature is over the DER of the SET OF
            // signed attributes (re-tagged from the IMPLICIT [0] to the SET tag).
            Some(signed_attrs) => {
                let want_digest = digest_for(&signer_info.digest_alg.oid, econtent_value)
                    .ok_or_else(|| "unsupported SignerInfo digestAlgorithm".to_string())?;
                let md = message_digest_attr(signed_attrs)
                    .ok_or_else(|| "SignerInfo signed attrs lack a message-digest".to_string())?;
                if md != want_digest.as_slice() {
                    return Err(
                        "SignerInfo message-digest attr does not equal digest(eContent)".to_string(),
                    );
                }
                // Re-encode the signed attrs under the SET OF tag (DER), which is
                // what RFC 5652 §5.4 says is signed (not the IMPLICIT [0] form).
                signed_attrs
                    .to_der()
                    .map_err(|e| format!("re-encoding signed attrs failed: {e}"))?
            }
            // No signed attributes: the eContent itself is the signed message.
            None => econtent_value.to_vec(),
        };

        let sig = signer_info.signature.as_bytes();
        let spki = cert.tbs_certificate().subject_public_key_info();
        // Some TSAs (e.g. DigiCert) label the SignerInfo signatureAlgorithm with the
        // bare `rsaEncryption` OID and name the hash only in `digestAlgorithm`. Pass
        // the SignerInfo digest OID so `verify_signature` can resolve the hash in
        // that case.
        verify_signature(
            &signer_info.signature_algorithm.oid,
            Some(&signer_info.digest_alg.oid),
            spki,
            &signed_message,
            sig,
        )
    }

    /// Extract the `message-digest` signed attribute's OCTET STRING value.
    fn message_digest_attr(attrs: &cms::signed_data::SignedAttributes) -> Option<Vec<u8>> {
        for attr in attrs.iter() {
            if attr.oid == ID_MESSAGE_DIGEST {
                let any = attr.values.as_slice().first()?;
                let octets = any.decode_as::<OctetString>().ok()?;
                return Some(octets.as_bytes().to_vec());
            }
        }
        None
    }

    /// Digest `data` under the SignerInfo digest-algorithm OID (SHA-256/384/512).
    fn digest_for(oid: &ObjectIdentifier, data: &[u8]) -> Option<Vec<u8>> {
        use sha2::Digest;
        match oid.to_string().as_str() {
            // id-sha256
            "2.16.840.1.101.3.4.2.1" => Some(sha2::Sha256::digest(data).to_vec()),
            // id-sha384
            "2.16.840.1.101.3.4.2.2" => Some(sha2::Sha384::digest(data).to_vec()),
            // id-sha512
            "2.16.840.1.101.3.4.2.3" => Some(sha2::Sha512::digest(data).to_vec()),
            _ => None,
        }
    }

    /// id-sha256 / id-sha384 / id-sha512 OIDs — the SignerInfo `digestAlgorithm`
    /// names the hash here when the signatureAlgorithm is the bare `rsaEncryption`.
    const ID_SHA256_DIGEST: &str = "2.16.840.1.101.3.4.2.1";
    const ID_SHA384_DIGEST: &str = "2.16.840.1.101.3.4.2.2";
    const ID_SHA512_DIGEST: &str = "2.16.840.1.101.3.4.2.3";

    /// Verify a certificate/SignerInfo signature over `message` under the public
    /// key in `spki`, dispatching on the signature-algorithm OID.
    ///
    /// Supported:
    /// - RSA PKCS#1 v1.5 under `sha{256,384,512}WithRSAEncryption`, AND under the
    ///   bare `rsaEncryption` OID (1.2.840.113549.1.1.1) — which some TSAs
    ///   (DigiCert) use on the SignerInfo, naming the hash only in the SignerInfo
    ///   `digestAlgorithm`. `digest_oid` carries that hash for the bare case.
    /// - ECDSA under `ecdsa-with-SHA{256,384,512}`. The CURVE comes from the SPKI
    ///   (P-256 or P-384), the HASH from the OID; both are honoured independently
    ///   (e.g. freeTSA signs P-384 keys with SHA-512). Verification is done over an
    ///   explicit prehash so the hash is never silently taken from the curve.
    ///
    /// An unknown OID, an SPKI that is the wrong key type, a hash we cannot resolve,
    /// or a bad signature all fail closed.
    fn verify_signature(
        sig_alg_oid: &ObjectIdentifier,
        digest_oid: Option<&ObjectIdentifier>,
        spki: &x509_cert::spki::SubjectPublicKeyInfoOwned,
        message: &[u8],
        signature: &[u8],
    ) -> Result<(), String> {
        use sha2::Digest;
        let spki_der = spki.to_der().map_err(|e| format!("re-encoding SPKI failed: {e}"))?;

        let ok = match sig_alg_oid.to_string().as_str() {
            // --- RSA PKCS#1 v1.5 -------------------------------------------------
            // sha256WithRSAEncryption / sha384 / sha512: hash named by the OID.
            "1.2.840.113549.1.1.11" => verify_rsa::<sha2::Sha256>(&spki_der, message, signature)?,
            "1.2.840.113549.1.1.12" => verify_rsa::<sha2::Sha384>(&spki_der, message, signature)?,
            "1.2.840.113549.1.1.13" => verify_rsa::<sha2::Sha512>(&spki_der, message, signature)?,
            // rsaEncryption: the signatureAlgorithm does NOT name a hash, so resolve
            // it from the SignerInfo digestAlgorithm (RFC 5652 / RFC 8933).
            "1.2.840.113549.1.1.1" => {
                let digest_oid = digest_oid.ok_or_else(|| {
                    "rsaEncryption signature with no digestAlgorithm to resolve the hash".to_string()
                })?;
                match digest_oid.to_string().as_str() {
                    ID_SHA256_DIGEST => verify_rsa::<sha2::Sha256>(&spki_der, message, signature)?,
                    ID_SHA384_DIGEST => verify_rsa::<sha2::Sha384>(&spki_der, message, signature)?,
                    ID_SHA512_DIGEST => verify_rsa::<sha2::Sha512>(&spki_der, message, signature)?,
                    other => {
                        return Err(format!(
                            "unsupported digestAlgorithm OID {other} for rsaEncryption signature"
                        ))
                    }
                }
            }
            // --- ECDSA: curve from SPKI, hash from the OID -----------------------
            // ecdsa-with-SHA256
            "1.2.840.10045.4.3.2" => {
                verify_ecdsa(&spki_der, &sha2::Sha256::digest(message), signature)?
            }
            // ecdsa-with-SHA384
            "1.2.840.10045.4.3.3" => {
                verify_ecdsa(&spki_der, &sha2::Sha384::digest(message), signature)?
            }
            // ecdsa-with-SHA512 (e.g. freeTSA: P-384 key, SHA-512 digest)
            "1.2.840.10045.4.3.4" => {
                verify_ecdsa(&spki_der, &sha2::Sha512::digest(message), signature)?
            }
            other => return Err(format!("unsupported signature algorithm OID {other}")),
        };
        if ok {
            Ok(())
        } else {
            Err("signature verification failed".to_string())
        }
    }

    /// RSA PKCS#1 v1.5 verify under a hash `D` (SHA-256/384/512). The hash must
    /// carry its DigestInfo OID (`AssociatedOid`), which is how PKCS#1 v1.5 names
    /// the hash in the padded block.
    fn verify_rsa<D>(spki_der: &[u8], message: &[u8], signature: &[u8]) -> Result<bool, String>
    where
        D: rsa::signature::digest::Digest + const_oid::AssociatedOid,
    {
        use rsa::pkcs1v15::{Signature as RsaSignature, VerifyingKey};
        use rsa::pkcs8::DecodePublicKey;
        use rsa::signature::Verifier;

        let sig = RsaSignature::try_from(signature)
            .map_err(|e| format!("signature is not a valid RSA signature: {e}"))?;
        let vk = VerifyingKey::<D>::from_public_key_der(spki_der)
            .map_err(|e| format!("public key is not RSA: {e}"))?;
        Ok(vk.verify(message, &sig).is_ok())
    }

    /// ECDSA verify over an explicit `prehash` (the already-computed message
    /// digest) and a DER-encoded signature (the X.509 / CMS form).
    ///
    /// The curve is taken from the SPKI: we try P-256 then P-384 (the curves in
    /// the dependency set). Verifying against an explicit prehash — rather than the
    /// curve verifier's built-in `Verifier`, which hardcodes the curve's default
    /// hash — lets the HASH be chosen by the signatureAlgorithm OID independently
    /// of the curve (so e.g. a P-384 key signed with SHA-512 verifies correctly).
    /// `bits2field` inside `verify_prehash` performs the RFC-6979 / X9.62 leftmost-
    /// bits truncation, so any digest length is handled per spec. A wrong key type
    /// or a malformed/invalid signature fails closed.
    fn verify_ecdsa(spki_der: &[u8], prehash: &[u8], signature: &[u8]) -> Result<bool, String> {
        // `signature` is not a direct dep of the lib (only a dev-dep); reach the
        // `PrehashVerifier` trait through `ecdsa`'s re-export, which is a `tsa` dep
        // and is the SAME `signature` crate instance p256/p384's keys implement.
        use ecdsa::signature::hazmat::PrehashVerifier;

        if let Ok(vk) = {
            use p256::pkcs8::DecodePublicKey;
            p256::ecdsa::VerifyingKey::from_public_key_der(spki_der)
        } {
            let sig = p256::ecdsa::DerSignature::try_from(signature)
                .map_err(|e| format!("signature is not a valid P-256 ECDSA signature: {e}"))?;
            return Ok(vk.verify_prehash(prehash, &sig).is_ok());
        }

        if let Ok(vk) = {
            use p384::pkcs8::DecodePublicKey;
            p384::ecdsa::VerifyingKey::from_public_key_der(spki_der)
        } {
            let sig = p384::ecdsa::DerSignature::try_from(signature)
                .map_err(|e| format!("signature is not a valid P-384 ECDSA signature: {e}"))?;
            return Ok(vk.verify_prehash(prehash, &sig).is_ok());
        }

        Err("ECDSA public key is neither P-256 nor P-384".to_string())
    }
}

